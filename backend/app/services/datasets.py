"""Authentic dataset handling with machine-readable provenance.

Source files come only from Project Gutenberg, downloaded as published. Two clearly labelled kinds of
workload may be derived from them, and are never presented as separately published originals:

  * exact copies: the same local file ingested under another logical name (label ``workload_copy``)
  * transformed files: a documented byte-level edit of one original (kind ``transformed``)

No text is invented. The only bytes a transformation adds are a single newline or one replaced byte.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import urlsplit

import httpx
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.db import session_scope
from app.core.errors import AppError, NotFoundError, ValidationFailure
from app.models.entities import DatasetSource
from app.services import audit, ingest
from app.services.context import AppContext
from app.services.hashing import sha256_file

ORGANIZATION = "Project Gutenberg (Project Gutenberg Literary Archive Foundation)"
LICENSE_NOTE = (
    "Public domain in the USA, distributed under the Project Gutenberg License "
    "(https://www.gutenberg.org/policy/license.html)."
)
ALLOWED_HOSTS = {"gutenberg.pglaf.org"}
# Project Gutenberg's website is for human readers: automated access to it is not permitted, and its policy
# directs automated tools to mirrors (https://www.gutenberg.org/policy/robot_access.html). This tool therefore
# downloads from the mirror run by the Project Gutenberg Literary Archive Foundation, with a delay between requests.
MIRROR_BASE = "https://gutenberg.pglaf.org/cache/epub"
USER_AGENT = "hdfs-optimizer-academic-project/1.0 (dataset download for storage evaluation)"
POLITE_DELAY_SECONDS = 2.0


@dataclass(frozen=True)
class CatalogEntry:
    ebook_id: int
    title: str
    author: str
    formats: tuple[str, ...] = ("txt",)


# The first three are the documents suggested by the project brief.
CATALOG: tuple[CatalogEntry, ...] = (
    CatalogEntry(1342, "Pride and Prejudice", "Jane Austen", ("txt", "html", "epub")),
    CatalogEntry(11, "Alice's Adventures in Wonderland", "Lewis Carroll", ("txt", "html", "epub")),
    CatalogEntry(1661, "The Adventures of Sherlock Holmes", "Arthur Conan Doyle", ("txt", "html", "epub")),
    CatalogEntry(84, "Frankenstein; Or, The Modern Prometheus", "Mary Wollstonecraft Shelley"),
    CatalogEntry(345, "Dracula", "Bram Stoker"),
    CatalogEntry(98, "A Tale of Two Cities", "Charles Dickens"),
    CatalogEntry(2701, "Moby Dick; Or, The Whale", "Herman Melville"),
    CatalogEntry(100, "The Complete Works of William Shakespeare", "William Shakespeare"),
    CatalogEntry(2600, "War and Peace", "Leo Tolstoy"),
)

_MIRROR_SUFFIX = {"txt": ".txt", "html": "-images.html", "epub": "-images-3.epub"}
_FORMAT_EXTENSION = {"txt": "txt", "html": "html", "epub": "epub"}

TRANSFORMATIONS = {
    "truncate_90": "Kept the first 90% of the original bytes and removed the rest.",
    "prefix_newline": "Inserted one newline byte (0x0A) before the first original byte, shifting every later byte by one.",
    "replace_mid_byte": "Replaced the single byte at the file's midpoint with a different byte, keeping the length unchanged.",
}


def source_page(ebook_id: int) -> str:
    return f"https://www.gutenberg.org/ebooks/{ebook_id}"


def download_url(ebook_id: int, file_format: str) -> str:
    return f"{MIRROR_BASE}/{ebook_id}/pg{ebook_id}{_MIRROR_SUFFIX[file_format]}"


def _read_manifest(path: Path) -> dict:
    if path.exists():
        return json.loads(path.read_text())
    return {
        "description": "Provenance of every dataset file used by HDFS Optimizer. Generated by the download "
        "tool; do not edit by hand.",
        "files": [],
    }


def _write_manifest(path: Path, manifest: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    manifest["number_of_files"] = len(manifest["files"])
    manifest["number_of_original_files"] = sum(1 for f in manifest["files"] if f["kind"] == "original")
    manifest["total_size_bytes"] = sum(f["size_bytes"] for f in manifest["files"])
    path.write_text(json.dumps(manifest, indent=2) + "\n")


def _header_title(path: Path) -> str | None:
    """Read the title Project Gutenberg prints in a plain-text file, to confirm the right book arrived."""
    if path.suffix != ".txt":
        return None
    with open(path, encoding="utf-8", errors="replace") as handle:
        for line in handle.read(4096).splitlines():
            if line.lstrip("﻿").startswith("The Project Gutenberg eBook of "):
                return line.lstrip("﻿").removeprefix("The Project Gutenberg eBook of ").strip()
            if line.lstrip("﻿").startswith("Title: "):
                return line.lstrip("﻿").removeprefix("Title: ").strip()
    return None


def download_catalog(
    dataset_dir: Path,
    provenance_path: Path,
    *,
    ebook_ids: list[int] | None = None,
    log=print,
) -> dict:
    """Download originals that are not already present. Existing records and bytes are never rewritten."""
    originals = dataset_dir / "originals"
    originals.mkdir(parents=True, exist_ok=True)
    manifest = _read_manifest(provenance_path)
    known = {(f["ebook_id"], f["file_format"]): f for f in manifest["files"] if f["kind"] == "original"}
    selected = [e for e in CATALOG if ebook_ids is None or e.ebook_id in ebook_ids]
    summary = {"downloaded": 0, "already_present": 0, "failed": []}

    with httpx.Client(follow_redirects=True, timeout=120, headers={"User-Agent": USER_AGENT}) as client:
        for entry in selected:
            for file_format in entry.formats:
                filename = f"pg{entry.ebook_id}.{_FORMAT_EXTENSION[file_format]}"
                target = originals / filename
                record = known.get((entry.ebook_id, file_format))
                if record and target.exists() and sha256_file(target)[0] == record["sha256"]:
                    summary["already_present"] += 1
                    continue
                url = download_url(entry.ebook_id, file_format)
                try:
                    response = client.get(url)
                    response.raise_for_status()
                    final_url = str(response.url)
                    host = urlsplit(final_url).hostname
                    if host not in ALLOWED_HOSTS:
                        raise AppError(f"Redirected to an unexpected host: {host}")
                except (httpx.HTTPError, AppError) as exc:
                    summary["failed"].append({"url": url, "error": str(exc)})
                    log(f"FAILED {url}: {exc}")
                    continue
                target.write_bytes(response.content)
                digest, size = sha256_file(target)
                new_record = {
                    "title": entry.title,
                    "author": entry.author,
                    "ebook_id": entry.ebook_id,
                    "source_organization": ORGANIZATION,
                    "source_url": source_page(entry.ebook_id),
                    "requested_url": url,
                    "actual_download_url": final_url,
                    "download_date": datetime.now(UTC).isoformat(),
                    "file_format": file_format,
                    "file_size": size,
                    "size_bytes": size,
                    "sha256": digest,
                    "kind": "original",
                    "transformations": "None. Stored exactly as served by the publisher.",
                    "header_title_in_file": _header_title(target),
                    "local_path": f"originals/{filename}",
                    "license_note": LICENSE_NOTE,
                }
                manifest["files"] = [
                    f for f in manifest["files"]
                    if not (f.get("ebook_id") == entry.ebook_id and f.get("file_format") == file_format and f["kind"] == "original")
                ] + [new_record]
                _write_manifest(provenance_path, manifest)
                summary["downloaded"] += 1
                log(f"downloaded {filename}: {size} bytes, sha256 {digest}")
                time.sleep(POLITE_DELAY_SECONDS)
    _write_manifest(provenance_path, manifest)
    return summary


def build_transformed_workload(dataset_dir: Path, provenance_path: Path, *, ebook_id: int = 1342) -> list[dict]:
    """Create documented partial-overlap files from one original plain-text book. Repeatable."""
    manifest = _read_manifest(provenance_path)
    source = next(
        (f for f in manifest["files"] if f["kind"] == "original" and f["ebook_id"] == ebook_id and f["file_format"] == "txt"),
        None,
    )
    if source is None:
        raise ValidationFailure(f"Download the plain-text original of ebook {ebook_id} first.")
    original = (dataset_dir / source["local_path"]).read_bytes()
    workload = dataset_dir / "workload"
    workload.mkdir(parents=True, exist_ok=True)
    midpoint = len(original) // 2
    replacement = b"X" if original[midpoint:midpoint + 1] != b"X" else b"Y"
    variants = {
        "truncate_90": original[: int(len(original) * 0.9)],
        "prefix_newline": b"\n" + original,
        "replace_mid_byte": original[:midpoint] + replacement + original[midpoint + 1 :],
    }
    created = []
    manifest["files"] = [
        f for f in manifest["files"]
        if not (f["kind"] == "transformed" and f.get("derived_from_sha256") == source["sha256"])
    ]
    for name, data in variants.items():
        filename = f"pg{ebook_id}.{name}.txt"
        path = workload / filename
        path.write_bytes(data)
        digest, size = sha256_file(path)
        record = {
            "title": f"{source['title']} (test workload: {name})",
            "author": source["author"],
            "ebook_id": ebook_id,
            "source_organization": "Derived locally by this project; not published by the source organization.",
            "source_url": source["source_url"],
            "requested_url": None,
            "actual_download_url": None,
            "download_date": None,
            "file_format": "txt",
            "file_size": size,
            "size_bytes": size,
            "sha256": digest,
            "kind": "transformed",
            "derived_from_sha256": source["sha256"],
            "transformations": TRANSFORMATIONS[name],
            "local_path": f"workload/{filename}",
            "license_note": LICENSE_NOTE,
        }
        manifest["files"].append(record)
        created.append(record)
    _write_manifest(provenance_path, manifest)
    return created


