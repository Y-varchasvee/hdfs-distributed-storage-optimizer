def sync_provenance(ctx: AppContext, session: Session) -> int:
    """Mirror the provenance file into the database. Returns the number of new rows."""
    manifest = _read_manifest(ctx.settings.provenance_path)
    existing = {row.sha256: row for row in session.scalars(select(DatasetSource))}
    added = 0
    for record in manifest["files"]:
        if record["sha256"] in existing:
            continue
        row = DatasetSource(
            title=record["title"],
            author=record.get("author"),
            ebook_id=record.get("ebook_id"),
            source_url=record.get("source_url"),
            download_url=record.get("actual_download_url"),
            organization=record.get("source_organization"),
            downloaded_at=_parse_date(record.get("download_date")),
            file_format=record["file_format"],
            size_bytes=record["size_bytes"],
            sha256=record["sha256"],
            kind=record["kind"],
            transformation=record.get("transformations") if record["kind"] != "original" else None,
            local_path=record["local_path"],
            license_note=record.get("license_note"),
        )
        session.add(row)
        existing[row.sha256] = row
        added += 1
    session.flush()
    for record in manifest["files"]:
        parent = existing.get(record.get("derived_from_sha256") or "")
        if parent is not None:
            existing[record["sha256"]].derived_from_id = parent.id
    session.flush()
    return added


def _parse_date(value: str | None) -> datetime | None:
    return datetime.fromisoformat(value).replace(tzinfo=None) if value else None


def source_dict(row: DatasetSource, *, local_present: bool | None = None) -> dict:
    return {
        "id": row.id,
        "title": row.title,
        "author": row.author,
        "ebook_id": row.ebook_id,
        "source_url": row.source_url,
        "download_url": row.download_url,
        "organization": row.organization,
        "downloaded_at": row.downloaded_at,
        "file_format": row.file_format,
        "size_bytes": row.size_bytes,
        "sha256": row.sha256,
        "kind": row.kind,
        "derived_from_id": row.derived_from_id,
        "transformation": row.transformation,
        "license_note": row.license_note,
        "local_present": local_present,
    }


def run_import(ctx: AppContext, job_id: str, params: dict, reporter) -> dict:
    """Job: download from the publisher, derive workload files, record provenance."""
    ebook_ids = params.get("ebook_ids")
    reporter.progress(0, 2, "Downloading from Project Gutenberg")
    summary = download_catalog(ctx.settings.dataset_dir, ctx.settings.provenance_path, ebook_ids=ebook_ids, log=lambda _: None)
    reporter.progress(1, 2, "Building documented workload files")
    derived = []
    if (ebook_ids is None or 1342 in ebook_ids) and not summary["failed"]:
        derived = build_transformed_workload(ctx.settings.dataset_dir, ctx.settings.provenance_path)
    with session_scope(ctx.session_factory) as session:
        added = sync_provenance(ctx, session)
        audit.record(
            session,
            "dataset.imported",
            f"Downloaded {summary['downloaded']} files ({summary['already_present']} already present, "
            f"{len(summary['failed'])} failed).",
            severity="warning" if summary["failed"] else "info",
            details={"failed": summary["failed"]},
        )
    reporter.progress(2, 2, "Done")
    return {
        **summary,
        "derived_files": len(derived),
        "rows_added": added,
        "errors": [f"{f['url']}: {f['error']}" for f in summary["failed"]],
    }


def run_ingest(ctx: AppContext, job_id: str, params: dict, reporter) -> dict:
    """Job: load dataset files into HDFS through the normal upload pipeline, labelling every copy."""
    source_ids: list[str] = params["source_ids"]
    copies: int = params.get("copies", 0)
    folder = params.get("folder", "/datasets")
    results, errors = [], []
    total = len(source_ids) * (copies + 1)
    done = 0
    reporter.progress(0, total, "Ingesting dataset files")
    for source_id in source_ids:
        with session_scope(ctx.session_factory) as session:
            source = session.get(DatasetSource, source_id)
            if source is None:
                raise NotFoundError(f"No dataset source {source_id}.")
            local, expected, kind = ctx.settings.dataset_dir / source.local_path, source.sha256, source.kind
        if not local.exists():
            errors.append(f"{local.name}: not present locally. Import the dataset first.")
            continue
        hash_started = time.perf_counter()
        digest = sha256_file(local)
        hash_ms = (time.perf_counter() - hash_started) * 1000
        if digest[0] != expected:
            errors.append(f"{local.name}: local bytes no longer match the recorded SHA-256; refusing to ingest.")
            continue
        for copy_index in range(copies + 1):
            if copy_index == 0:
                name, label = local.name, kind if kind != "original" else "dataset_original"
            else:
                name, label = f"{local.stem}__workload-copy-{copy_index}{local.suffix}", "workload_copy"
            outcome = ingest.ingest_local_file(
                ctx,
                local,
                name,
                folder=folder,
                mode=params.get("mode"),
                chunk_size=params.get("chunk_size"),
                provenance_label=label,
                dataset_source_id=source_id,
                known_hash=digest,
                known_hash_ms=hash_ms if copy_index == 0 else None,  # copies reuse the same hash
            )
            results.append({"file_id": outcome.file.id, "name": outcome.file.name, "outcome": outcome.outcome, "label": label})
            done += 1
            reporter.progress(done, total, f"Ingested {done} of {total}")
    return {"ingested": len(results), "files": results, "errors": errors}
